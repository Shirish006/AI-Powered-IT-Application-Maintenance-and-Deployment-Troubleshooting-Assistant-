    def load_session(self, session_id: int) -> None:
        """Load and render an existing analyzed session from SQLite without calling AI."""
        session = self.db.get_session(session_id)
        if not session:
            QMessageBox.warning(self, "Session Not Found", f"Session #{session_id} could not be retrieved from database.")
            return

        self.current_session = session

        # Header values
        summary = session.get("error_summary", "Unspecified Error")
        self.summary_label.setText(f"#{session['id']} - {summary}")

        # Badges
        lang = session.get("programming_language", "Python")
        self.badge_lang.set_badge(lang, "neutral")

        ptype = session.get("problem_type", "Maintenance")
        if session.get("detected_problem_type") and ptype == "Automatic Detection":
            ptype = f"{session['detected_problem_type']} (auto)"
        self.badge_type.set_badge(ptype, "neutral")

        cat = session.get("error_category", "Runtime Error")
        self.badge_category.set_badge(cat, "neutral")

        sev = session.get("severity", "Medium")
        self.badge_severity.set_badge(f"Severity: {sev}", sev)

        status = session.get("resolution_status", "Unresolved")
        self.badge_status.set_badge(status, status)

        # Sync dropdown without triggering duplicate DB update
        self.status_combo.blockSignals(True)
        idx = self.status_combo.findText(status)
        if idx >= 0:
            self.status_combo.setCurrentIndex(idx)
        self.status_combo.blockSignals(False)

        # Mark as Resolved button state
        if status == "Solved":
            self.resolve_btn.setEnabled(False)
            self.resolve_btn.setText("✓ Solved")
        else:
            self.resolve_btn.setEnabled(True)
            self.resolve_btn.setText("✓ Mark as Resolved")

        # Demo Banner
        if session.get("is_demo"):
            self.demo_banner.show()
        else:
            self.demo_banner.hide()

        # Explanation
        self.explanation_text.setText(session.get("error_explanation", "No explanation available."))

        # Confirmed Facts vs Possible Causes
        facts = session.get("confirmed_facts", [])
        if isinstance(facts, list) and facts:
            self.facts_label.setText("\n".join(f"• {f}" for f in facts))
        else:
            self.facts_label.setText("No specific facts extracted.")

        causes = session.get("possible_causes", [])
        if isinstance(causes, list) and causes:
            self.causes_label.setText("\n".join(f"• {c}" for c in causes))
        else:
            self.causes_label.setText("No specific causes identified.")

        # Troubleshooting Steps
        steps = session.get("troubleshooting_steps", [])
        if isinstance(steps, list) and steps:
            formatted_steps = []
            for i, step in enumerate(steps, 1):
                clean_step = step.lstrip("0123456789.- ")
                formatted_steps.append(f"{i}. {clean_step}")
            self.steps_label.setText("\n\n".join(formatted_steps))
        else:
            self.steps_label.setText("No troubleshooting steps recorded.")

        # Suggested Solution
        self.solution_text.setPlainText(session.get("suggested_solution", "No solution provided."))

        # Verification Steps
        vsteps = session.get("verification_steps", [])
        if isinstance(vsteps, list) and vsteps:
            formatted_vsteps = []
            for i, vstep in enumerate(vsteps, 1):
                clean_vstep = vstep.lstrip("0123456789.- ")
                formatted_vsteps.append(f"{i}. {clean_vstep}")
            self.verification_label.setText("\n\n".join(formatted_vsteps))
        else:
            self.verification_label.setText("No verification steps recorded.")

        # Original Log
        self.log_text.setPlainText(session.get("original_error_log", ""))

    def _on_status_dropdown_changed(self, new_status: str) -> None:
        """Handle user changing status via dropdown."""
        if not self.current_session:
            return
        session_id = self.current_session["id"]
        try:
            self.db.update_status(session_id, new_status)
            self.current_session["resolution_status"] = new_status
            self.badge_status.set_badge(new_status, new_status)

            if new_status == "Solved":
                self.resolve_btn.setEnabled(False)
                self.resolve_btn.setText("✓ Solved")
            else:
                self.resolve_btn.setEnabled(True)
                self.resolve_btn.setText("✓ Mark as Resolved")
        except Exception as e:
            QMessageBox.critical(self, "Update Error", f"Failed to update status: {e}")

    def _on_mark_resolved_clicked(self) -> None:
        """One-click resolution handler."""
        if not self.current_session:
            return
        session_id = self.current_session["id"]
        try:
            self.db.update_status(session_id, "Solved")
            self.current_session["resolution_status"] = "Solved"
            self.badge_status.set_badge("Solved", "Solved")
            self.status_combo.blockSignals(True)
            self.status_combo.setCurrentText("Solved")
            self.status_combo.blockSignals(False)
            self.resolve_btn.setEnabled(False)
            self.resolve_btn.setText("✓ Solved")
            QMessageBox.information(self, "Resolved", f"Session #{session_id} marked as Solved.")
        except Exception as e:
            QMessageBox.critical(self, "Update Error", f"Failed to mark as resolved: {e}")

    def _on_try_again_clicked(self) -> None:
        """Return to Screen 2 with inputs preserved for editing and re-analysis."""
        if not self.current_session:
            return

        payload = {
            "language": self.current_session.get("programming_language", "Python"),
            "problem_type": self.current_session.get("problem_type", "Automatic Detection"),
            "environment": self.current_session.get("environment", "Development"),
            "framework": self.current_session.get("application_framework", ""),
            "error_log": self.current_session.get("original_error_log", ""),
        }
        self.try_again_requested.emit(payload)

